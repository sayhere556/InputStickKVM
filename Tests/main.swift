import Foundation

var checks = 0
func expect(_ value: @autoclosure () -> Bool, _ message: String) {
    checks += 1
    guard value() else { fatalError("FAILED: \(message)") }
}

var capture = CaptureSession()
capture.begin(ready: false)
expect(!capture.active, "Disconnected capture must be blocked")
capture.begin(ready: true)
expect(capture.forwarding && !capture.cursorLocked, "Capture starts unlocked")
capture.toggleLock(ready: true)
expect(!capture.lockRequested, "Lock cannot change without Right Command")
capture.rightCommandDown = true
expect(!capture.forwarding, "Right Command pauses forwarding")
capture.toggleLock(ready: true)
expect(capture.lockRequested && !capture.cursorLocked, "Lock waits for Command release")
capture.rightCommandDown = false
expect(capture.cursorLocked, "Command release activates requested lock")
capture.rightCommandDown = true
expect(!capture.cursorLocked, "Command restores local pointer")
capture.toggleLock(ready: true)
capture.rightCommandDown = false
expect(capture.forwarding && !capture.cursorLocked, "Unlock returns to window control")
capture.release()
expect(!capture.forwarding && !capture.lockRequested, "Escape/focus/disconnect release resets capture")
capture.rightCommandDown = true
capture.begin(ready: true)
expect(!capture.active, "Cannot activate while local controls are held")

capture = CaptureSession()
expect(!capture.updateControlKey(deviceFlags: 0x8), "Left Command does not reveal local controls")
capture.begin(ready: true)
expect(capture.forwarding, "Left Command does not pause forwarding")
expect(capture.updateControlKey(deviceFlags: 0x18), "Right Command is detected with both Commands held")
expect(!capture.forwarding, "Both Commands held pauses forwarding")
expect(!capture.updateControlKey(deviceFlags: 0x10), "Releasing Left Command does not resume capture")
expect(capture.updateControlKey(deviceFlags: 0x8), "Releasing Right Command resumes with Left still held")
expect(capture.forwarding, "Forwarding resumes on Right Command release")
capture.release()
_ = capture.updateControlKey(deviceFlags: 0x10)
capture.begin(ready: true)
expect(!capture.active, "Right Command on the initial mouse event blocks capture")
capture.toggleLock(ready: true)
expect(!capture.lockRequested, "Inactive session cannot request lock")
_ = capture.updateControlKey(deviceFlags: 0)
capture.begin(ready: true)
_ = capture.updateControlKey(deviceFlags: 0x10)
capture.toggleLock(ready: false)
expect(!capture.lockRequested, "Disconnected session cannot request lock")
capture.toggleLock(ready: true)
capture.release()
_ = capture.updateControlKey(deviceFlags: 0)
expect(!capture.cursorLocked && !capture.active, "Release during Command pause prevents relocking")

var keyboard = HIDKeyboardState()
keyboard.update(keyCode: 0, down: true)
keyboard.update(keyCode: 1, down: true)
expect(Array(keyboard.report) == [0,0,4,22,0,0,0,0], "Simultaneous A + S")
keyboard.update(keyCode: 0, down: false)
expect(Array(keyboard.report) == [0,0,22,0,0,0,0,0], "Releasing one key preserves another")
keyboard.updateModifiers(deviceFlags: 0x10)
expect(keyboard.modifiers == 0, "Right Command must never reach Windows")
keyboard.updateModifiers(deviceFlags: 0x8)
expect(keyboard.modifiers == 0x08, "Left Command is left Windows key")
keyboard.updateModifiers(deviceFlags: 0x18)
expect(keyboard.modifiers == 0x08, "Both Commands never leak reserved Right Command to the host")
keyboard.updateModifiers(deviceFlags: 0x2067)
expect(keyboard.modifiers == 0x77, "Both sides of Control/Shift/Alt")
keyboard.reset()
for key: UInt16 in [0,1,2,3,4,5,6] { keyboard.update(keyCode: key, down: true) }
expect(Array(keyboard.report).suffix(6).allSatisfy { $0 == 1 }, "Seven-key rollover uses HID error report")
keyboard.update(keyCode: 6, down: false)
expect(!Array(keyboard.report).suffix(6).contains(1), "Recovery after rollover")
keyboard.reset()
expect(Array(keyboard.report) == Array(repeating: 0, count: 8), "Neutral report releases all keys")
keyboard.update(keyCode: 999, down: true)
expect(keyboard.keys.isEmpty, "Unsupported keys are ignored")

var mouse = MouseAccumulator()
mouse.add(x: 300.5, y: -250.5, wheel: 2.5)
let first = mouse.take()
expect(first.0 == 127 && first.1 == -127 && first.2 == 2, "Mouse reports clamp signed HID range")
let second = mouse.take()
expect(second.0 == 127 && second.1 == -123, "Excess motion is preserved")
let third = mouse.take()
expect(third.0 == 46 && third.1 == 0 && third.2 == 0, "Fractional movement is retained")
mouse.add(x: 0.5, y: -0.5, wheel: 0.5)
let fourth = mouse.take()
expect(fourth.0 == 1 && fourth.1 == -1 && fourth.2 == 1, "Subpixel deltas accumulate")
mouse.add(x: 100000, y: -100000)
expect(mouse.x == 512 && mouse.y == -512, "Backlog is bounded")
// Discovery/reconnect is tested with a fake clock and no Bluetooth access.
func nextAction(_ policy: inout ConnectionAutomation, at time: Double, powered: Bool = true,
                state: Int = 0, scanning: Bool = false, discover: Bool = true,
                reconnect: Bool = true, known: String? = "remembered") -> ConnectionAction? {
    policy.next(now: time, bluetoothOn: powered, connectionState: state, scanning: scanning,
                discover: discover, reconnect: reconnect, rememberedID: known)
}
var policy = ConnectionAutomation()
expect(nextAction(&policy, at: 0, powered: false) == nil, "No attempts while Bluetooth is off")
expect(nextAction(&policy, at: 0) == .connect("remembered"), "Reconnect only to remembered receiver")
expect(nextAction(&policy, at: 1, discover: false) == nil, "Retry delay prevents rapid reconnect loops")
expect(nextAction(&policy, at: 2) == .connect("remembered"), "Retry after two seconds")
expect(policy.nextAttempt == 6, "Retry delay increases")
expect(nextAction(&policy, at: 6, state: 1) == nil, "No overlapping connection attempts")
expect(nextAction(&policy, at: 6, state: 3) == nil, "Do not reconnect while waiting for USB")
expect(nextAction(&policy, at: 6, state: 4) == nil, "Do not reconnect while USB sleeps")
expect(nextAction(&policy, at: 6, state: 5) == nil && policy.attempts == 0, "Ready resets backoff without capturing input")
expect(nextAction(&policy, at: 7, discover: false) == nil, "Brief grace period after link loss")
expect(nextAction(&policy, at: 8) == .connect("remembered"), "Link loss retries known receiver")
policy.paused = true
expect(nextAction(&policy, at: 100) == nil, "Manual disconnect stops all automatic actions")
policy.resume()
expect(nextAction(&policy, at: 100) == .connect("remembered"), "Explicit resume allows reconnect")
policy = ConnectionAutomation()
expect(nextAction(&policy, at: 0, known: nil) == .scan, "First launch discovers but never connects to a stranger")
expect(nextAction(&policy, at: 1, known: nil) == nil, "Scan start is throttled")
expect(nextAction(&policy, at: 20, scanning: true, known: nil) == nil, "Do not restart an active scan")
expect(nextAction(&policy, at: 20, known: nil) == .scan, "Discovery resumes after scan timeout")
policy = ConnectionAutomation()
expect(nextAction(&policy, at: 0, discover: false, reconnect: false) == nil, "Both toggles off means no automatic actions")
expect(nextAction(&policy, at: 0, reconnect: false) == .scan, "Discovery can run without reconnect")
policy = ConnectionAutomation()
for time: Double in [0, 2, 6, 14, 30, 60, 90] { _ = nextAction(&policy, at: time, discover: false) }
expect(policy.nextAttempt == 120, "Retry interval caps at 30 seconds")

expect(ClipboardMacro.prepare("") == .failure(.empty), "Empty clipboard is not sent")
expect(ClipboardMacro.prepare("hello\r\nworld\r\t!") == .success("hello\nworld\n\t!"), "Normalize line endings and retain tabs")
expect(ClipboardMacro.prepare("café") == .failure(.unsupportedCharacters), "Reject unsupported text instead of silently dropping characters")
expect(ClipboardMacro.prepare("a\u{1B}b") == .failure(.unsupportedCharacters), "Reject embedded control characters")
expect(ClipboardMacro.prepare(String(repeating: "a", count: 100001)) == .failure(.tooLong), "Bound clipboard queue size")
var macroQueue = TextMacroQueue()
macroQueue.start(String(repeating: "a", count: 40))
expect(macroQueue.next(ready: true, keyboardIdle: false) == nil && macroQueue.queued == 0, "Wait for receiver buffer")
expect(macroQueue.next(ready: true, keyboardIdle: true)?.count == 32, "Bounded first clipboard chunk")
expect(macroQueue.next(ready: true, keyboardIdle: false) == nil, "No chunk while previous text is pending")
expect(macroQueue.next(ready: true, keyboardIdle: true)?.count == 8, "Final chunk preserves all remaining text")
expect(macroQueue.active, "Not complete until last remote chunk drains")
expect(macroQueue.next(ready: true, keyboardIdle: true) == nil && !macroQueue.active, "Completion waits for idle receiver")
macroQueue.start("private text")
macroQueue.cancel()
expect(macroQueue.next(ready: true, keyboardIdle: true) == nil && macroQueue.total == 0, "Cancel discards clipboard contents")
macroQueue.start("never replay")
expect(macroQueue.next(ready: false, keyboardIdle: true) == nil && !macroQueue.active, "Disconnect cancels macro")
expect(macroQueue.next(ready: true, keyboardIdle: true) == nil, "Reconnect never replays clipboard")
print("Passed \(checks) checks. No Bluetooth, clipboard reads, event hooks, or cursor changes used.")
